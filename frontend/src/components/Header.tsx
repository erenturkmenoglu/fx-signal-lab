import { timeUTC } from "../format";
import type { Link } from "../live";
import type { SystemStatus } from "../types";
import { StatePill, type Tone } from "./ui";

const PROVIDER: Record<SystemStatus["provider"]["label"], { tone: Tone; text: string }> = {
  LIVE: { tone: "ok", text: "Live market data" },
  MOCK: { tone: "warn", text: "Mock data" },
  "TEST ENDPOINT": { tone: "warn", text: "Test endpoint" },
  "NOT CONFIGURED": { tone: "bad", text: "No data provider" },
};

export function Header({ status, link }: { status: SystemStatus | null; link: Link }) {
  const provider = status?.provider;
  const badge = provider ? PROVIDER[provider.label] : null;
  const sessions = status?.sessions ?? [];
  return (
    <header className="flex flex-wrap items-center gap-x-6 gap-y-1 border-b border-line bg-panel px-3 py-2">
      <div className="flex items-baseline gap-2">
        <span className="text-[17px] font-semibold tracking-tight">FX Signal Lab</span>
        {status?.version ? <span className="note num">v{status.version}</span> : null}
      </div>

      {badge && provider ? (
        <div className="flex items-center gap-2">
          <StatePill tone={badge.tone}>{badge.text}</StatePill>
          {provider.label === "LIVE" ? <span className="note">Massive</span> : null}
          {provider.label === "TEST ENDPOINT" ? <span className="note num">{provider.feed_host}</span> : null}
        </div>
      ) : null}

      <div className="note" title="Regional sessions that are open right now (local business hours of each centre)">
        {sessions.length ? `Sessions open: ${sessions.join(", ")}` : status ? "Between sessions" : ""}
      </div>

      <div className="ml-auto flex items-center gap-4">
        {link !== "open" ? (
          <StatePill tone={link === "connecting" ? "idle" : "bad"}>
            {link === "connecting" ? "Connecting to backend" : "Backend unreachable, retrying"}
          </StatePill>
        ) : null}
        <span className="num text-[15px]" title="Backend clock, UTC">
          {timeUTC(status?.server_time_ms)} <span className="note">UTC</span>
        </span>
      </div>
    </header>
  );
}

